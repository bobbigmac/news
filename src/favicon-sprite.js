export function faviconSpriteId(host) {
  return String(host || '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

export function getFaviconSpriteClass(host) {
  return FAVICON_SPRITE_HOSTS.has(host) ? `source-icon-${faviconSpriteId(host)}` : '';
}
